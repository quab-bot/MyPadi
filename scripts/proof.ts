/**
 * Generate docs/PROOF.md from the service_calls table: one row per settled payment, with the
 * settlement tx hash (proof of payment) for the submission.
 *
 *   npm run proof
 *
 * Reads only rows that actually paid (status 'paid', tx_hash present). Unresolved/failed/free
 * calls are summarised in a footer but never listed as proof. Pure read; writes one markdown file.
 */

import { writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { getPool, closePool } from '../src/db/pool.js';
import { usdFromMicro } from '../src/budget/money.js';
import { REPO_ROOT } from '../src/config/golive.js';

interface Row {
  created_at: string;
  capability: string;
  url: string;
  network: string | null;
  token: string | null;
  paid_micro: string | null;
  tx_hash: string | null;
  prompt: string;
}

function host(url: string): string {
  try {
    return new URL(url).host;
  } catch {
    return url;
  }
}

async function main(): Promise<void> {
  const pool = getPool();
  // Every paid row is listed, INCLUDING any whose settlement tx hash did not come back from
  // `buy receipts` yet. Those are surfaced with a "(hash pending)" marker rather than silently
  // dropped, so the count here always matches the ledger's paid count. Resolve a pending hash with
  // `buy receipts --resolve`, then re-run this script.
  const paid = await pool.query<Row>(
    `SELECT sc.created_at, sc.capability, sc.url, sc.network, sc.token, sc.paid_micro, sc.tx_hash,
            t.prompt
       FROM service_calls sc
       JOIN tasks t ON t.id = sc.task_id
      WHERE sc.status = 'paid'
      ORDER BY sc.created_at`,
  );
  const summary = await pool.query<{ status: string; n: string; total: string | null }>(
    `SELECT status, COUNT(*) n, SUM(paid_micro) total FROM service_calls GROUP BY status ORDER BY status`,
  );
  const byNetwork = await pool.query<{ network: string | null; n: string; total: string | null }>(
    `SELECT network, COUNT(*) n, SUM(paid_micro) total
       FROM service_calls
      WHERE status = 'paid'
      GROUP BY network ORDER BY network`,
  );

  const lines: string[] = [];
  lines.push('# MyPadi proof of payment');
  lines.push('');
  lines.push('Generated by `npm run proof` from the `service_calls` table. Each row is a real x402');
  lines.push('payment made for the MyPadi project wallet. The Network column says whether a row settled');
  lines.push('on Celo mainnet (`celo`) or on Celo Sepolia testnet (`celo-sepolia`, from the sandbox');
  lines.push('build); see the per-network totals below. Do not hand-edit.');
  lines.push('');
  lines.push(`Generated: ${new Date().toISOString()}`);
  lines.push('');
  lines.push('| Date (UTC) | Service | Endpoint (host) | Price | Token | Network | Settlement tx | Task |');
  lines.push('|---|---|---|---|---|---|---|---|');

  if (paid.rowCount === 0) {
    lines.push('| _(none yet)_ | | | | | | | |');
  } else {
    for (const r of paid.rows) {
      const date = new Date(r.created_at).toISOString().slice(0, 16).replace('T', ' ');
      const price = r.paid_micro ? `$${usdFromMicro(Number(r.paid_micro))}` : '';
      const task = r.prompt.length > 60 ? r.prompt.slice(0, 57) + '...' : r.prompt;
      const tx = r.tx_hash ? `\`${r.tx_hash}\`` : '_(hash pending: `buy receipts --resolve`)_';
      lines.push(
        `| ${date} | ${r.capability} | ${host(r.url)} | ${price} | ${r.token ?? ''} | ${r.network ?? ''} | ${tx} | ${task.replace(/\|/g, '\\|')} |`,
      );
    }
  }

  lines.push('');
  lines.push('## Totals by status');
  lines.push('');
  lines.push('| Status | Count | Total paid |');
  lines.push('|---|---|---|');
  for (const s of summary.rows) {
    const total = s.total ? `$${usdFromMicro(Number(s.total))}` : '$0';
    lines.push(`| ${s.status} | ${s.n} | ${total} |`);
  }
  lines.push('');
  lines.push('## Paid settlements by network');
  lines.push('');
  lines.push('| Network | Paid calls | Total paid |');
  lines.push('|---|---|---|');
  for (const n of byNetwork.rows) {
    const total = n.total ? `$${usdFromMicro(Number(n.total))}` : '$0';
    const label = n.network ?? '(unknown)';
    lines.push(`| ${label} | ${n.n} | ${total} |`);
  }
  lines.push('');

  const path = join(REPO_ROOT, 'docs', 'PROOF.md');
  writeFileSync(path, lines.join('\n'), 'utf8');
  console.log(`Wrote ${path} (${paid.rowCount} paid call(s)).`);
  await closePool();
}

main().catch(async (err) => {
  console.error('proof failed:', err instanceof Error ? err.message : err);
  await closePool().catch(() => {});
  process.exit(1);
});
