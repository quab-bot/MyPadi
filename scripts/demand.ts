/**
 * Generate docs/DEMAND.md from the service_calls table: how much real, paid demand MyPadi has sent
 * to each external provider, and how that demand builds over time.
 *
 *   npm run demand
 *
 * "Build with buy" is judged partly on demand created for the services we pay. This report is the
 * honest, data-driven view of that: per-provider paid call counts and spend, and a per-day
 * breakdown so recurring usage (e.g. Watchtower re-checks) shows up as traffic over time. Pure read;
 * writes one markdown file. Every number comes from settled paid rows only; nothing is invented.
 */

import { writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { getPool, closePool } from '../src/db/pool.js';
import { usdFromMicro } from '../src/budget/money.js';
import { REPO_ROOT } from '../src/config/golive.js';

interface ProviderRow {
  capability: string;
  network: string | null;
  calls: string;
  total: string | null;
  first_day: string;
  last_day: string;
}

interface DayRow {
  day_utc: string;
  capability: string;
  network: string | null;
  calls: string;
  total: string | null;
}

async function main(): Promise<void> {
  const pool = getPool();

  const perProvider = await pool.query<ProviderRow>(
    `SELECT capability, network,
            COUNT(*) calls, SUM(paid_micro) total,
            MIN(created_at)::date::text first_day, MAX(created_at)::date::text last_day
       FROM service_calls
      WHERE status = 'paid'
      GROUP BY capability, network
      ORDER BY COUNT(*) DESC, capability`,
  );

  const perDay = await pool.query<DayRow>(
    `SELECT created_at::date::text AS day_utc, capability, network,
            COUNT(*) calls, SUM(paid_micro) total
       FROM service_calls
      WHERE status = 'paid'
      GROUP BY created_at::date, capability, network
      ORDER BY created_at::date, capability`,
  );

  const usd = (v: string | null): string => (v ? `$${usdFromMicro(Number(v))}` : '$0');

  const lines: string[] = [];
  lines.push('# MyPadi demand created (Build with buy)');
  lines.push('');
  lines.push('Generated by `npm run demand` from the `service_calls` table. This is the real, paid');
  lines.push('demand MyPadi has routed to each external provider through buy. Every number is from');
  lines.push('settled paid rows only (see `docs/PROOF.md` for the per-call tx hashes). Do not hand-edit.');
  lines.push('');
  lines.push(`Generated: ${new Date().toISOString()}`);
  lines.push('');
  lines.push('## Demand per provider');
  lines.push('');
  lines.push('| Provider (capability) | Network | Paid calls | Total paid | First | Last |');
  lines.push('|---|---|---|---|---|---|');
  if (perProvider.rowCount === 0) {
    lines.push('| _(none yet)_ | | | | | |');
  } else {
    for (const r of perProvider.rows) {
      lines.push(
        `| ${r.capability} | ${r.network ?? ''} | ${r.calls} | ${usd(r.total)} | ${r.first_day} | ${r.last_day} |`,
      );
    }
  }
  lines.push('');
  lines.push('## Demand over time (paid calls per day)');
  lines.push('');
  lines.push('| Day (UTC) | Provider (capability) | Network | Paid calls | Total paid |');
  lines.push('|---|---|---|---|---|');
  if (perDay.rowCount === 0) {
    lines.push('| _(none yet)_ | | | | |');
  } else {
    for (const r of perDay.rows) {
      lines.push(`| ${r.day_utc} | ${r.capability} | ${r.network ?? ''} | ${r.calls} | ${usd(r.total)} |`);
    }
  }
  lines.push('');
  lines.push('## Provider-side view');
  lines.push('');
  lines.push('Each paid call is a USDC transfer from the MyPadi agent wallet to the provider\'s');
  lines.push('recipient address, settled on Celo and visible on Celoscan. A provider can confirm the');
  lines.push('traffic we create independently, by the settlements their recipient address receives;');
  lines.push('the per-call settlement tx hashes in `docs/PROOF.md` link straight to those transfers.');
  lines.push('');

  const path = join(REPO_ROOT, 'docs', 'DEMAND.md');
  writeFileSync(path, lines.join('\n'), 'utf8');
  console.log(`Wrote ${path} (${perProvider.rowCount} provider(s), ${perDay.rowCount} day-rows).`);
  await closePool();
}

main().catch(async (err) => {
  console.error('demand failed:', err instanceof Error ? err.message : err);
  await closePool().catch(() => {});
  process.exit(1);
});
